/**
 * Build both halves of the plugin.
 *
 * Host half (`src/host/index.ts` → `lib/host.js`): plain ESM for Node. Every
 * bare import stays external because DSH provides those packages at runtime
 * (`~/.dsh/profiles/node_modules`), and bundling a second copy would break the
 * identity-sensitive pieces (schemastery volatile references, service classes).
 *
 * Client half (`src/client/index.ts` → `lib/client.js`): the browser module
 * system does not load ESM files. It expects a script that calls
 * `window.__ModuleLoader__.load({ id, factory(require) })`, with React and the
 * other platform modules resolved through the injected `require`. The wrapper
 * is supplied as esbuild banner/footer so source maps still line up.
 */
import { readFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { context } from 'esbuild'

const root = dirname(fileURLToPath(import.meta.url))
const pkg = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'))
const watch = process.argv.includes('--watch')

/** Modules the DSH browser kernel or the package graph owns at runtime. */
const CLIENT_EXTERNALS = [
  'react',
  'react/jsx-runtime',
  'react-dom',
  'react-dom/client',
  '@deepseek-ai/*',
]

/** @type {import('esbuild').BuildOptions} */
const host = {
  entryPoints: [resolve(root, 'src/host/index.ts')],
  outfile: resolve(root, 'lib/host.js'),
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: ['node22'],
  packages: 'external',
  sourcemap: true,
  logLevel: 'info',
}

/** @type {import('esbuild').BuildOptions} */
const client = {
  entryPoints: [resolve(root, 'src/client/index.ts')],
  outfile: resolve(root, 'lib/client.js'),
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: ['chrome100'],
  loader: { '.css': 'text' },
  external: CLIENT_EXTERNALS,
  banner: {
    js: [
      '/* Generated by build.mjs — do not edit. */',
      'window.__ModuleLoader__.load({',
      `  id: ${JSON.stringify(pkg.name)},`,
      '  factory: (require) => {',
      '    var module = { exports: {} };',
      '    var exports = module.exports;',
    ].join('\n'),
  },
  footer: {
    js: ['    return module.exports;', '  },', '});'].join('\n'),
  },
  sourcemap: true,
  logLevel: 'info',
}

if (watch) {
  const [hostCtx, clientCtx] = await Promise.all([context(host), context(client)])
  await Promise.all([hostCtx.watch(), clientCtx.watch()])
  console.log('dsh-tweakit: watching src/ (declarations are not re-emitted in watch mode)')
} else {
  const [hostCtx, clientCtx] = await Promise.all([context(host), context(client)])
  await Promise.all([hostCtx.rebuild(), clientCtx.rebuild()])
  await Promise.all([hostCtx.dispose(), clientCtx.dispose()])
  console.log('dsh-tweakit: built lib/host.js and lib/client.js')
}
